import path from 'path'
import fg from 'fast-glob'
import fs from 'fs-extra'
import { applyEdits, modify } from 'jsonc-parser'
import { ENGINE_LOCALES } from '../src/translators/locales'

/** Intl.DisplayNames 查不到名字的旗帜：英伦三岛 + 占位图，手工补 */
const FLAG_NAME_OVERRIDES: Record<string, string> = {
  'gb-eng': '英格兰',
  'gb-nir': '北爱尔兰',
  'gb-sct': '苏格兰',
  'gb-wls': '威尔士',
  unknown: '未知（占位图标）',
}

/** 翻译引擎 id → 说明，用于 translate.localeMap 的键提示 */
const TRANSLATE_ENGINES: Record<string, string> = {
  baidu: '百度翻译',
  google: 'Google 翻译',
  'google-cn': 'Google 翻译（国内镜像）',
  deepl: 'DeepL',
  libretranslate: 'LibreTranslate',
  openai: 'OpenAI（按语言名写进提示词，不做语言码转换）',
}

/** 把旗帜名翻成中文国家/地区名，作为 enumDescriptions */
function flagDescriptions(flags: string[]): string[] {
  const region = new Intl.DisplayNames(['zh-CN'], { type: 'region' })
  const language = new Intl.DisplayNames(['zh-CN'], { type: 'language' })
  // DisplayNames.of 对不合法的代码直接抛 RangeError（'zh' 不是地区、'gb-eng' 不是标准地区码）
  const safe = (fn: () => string | undefined) => {
    try {
      return fn()
    }
    catch {
      return undefined
    }
  }
  return flags.map((flag) => {
    if (FLAG_NAME_OVERRIDES[flag])
      return FLAG_NAME_OVERRIDES[flag]
    const asRegion = safe(() => region.of(flag.toUpperCase()))
    if (asRegion && asRegion !== flag.toUpperCase())
      return asRegion
    const asLanguage = safe(() => language.of(flag))
    if (asLanguage && asLanguage !== flag)
      return asLanguage
    return flag
  })
}

/**
 * 单个引擎的 localeMap 子 schema：左边是项目里的语言标识（动态，无法提示），
 * 右边是该引擎的语言码——用 enum 列出来，设置面板才会给出下拉，省得背 cht / jp / kor 这些码。
 * 清单来自 `src/translators/locales.ts`（引擎真正认的那套），与翻译链路同源。
 */
function engineLocaleSchema(id: string, label: string) {
  const seen = new Set<string>()
  const locales = (ENGINE_LOCALES[id] || []).filter((l) => {
    if (l.sourceOnly || seen.has(l.code))
      return false
    seen.add(l.code)
    return true
  })
  return {
    type: 'object',
    markdownDescription: `${label}：左边写你项目里的语言标识（文件名去后缀，如 \`zh-tw\`、\`chs\`），右边选该引擎的语言码。没有语言码概念的引擎（openai）直接写语言名。`,
    additionalProperties: locales.length
      ? {
          type: 'string',
          enum: locales.map(l => l.code),
          enumDescriptions: locales.map(l => l.name),
        }
      : { type: 'string' },
  }
}

/**
 * 把旗帜清单写进 package.json 的 schema。
 *
 * `i18n-ally.localeCountryMap` 的值是旗帜名（res/flags 的文件名），但 schema 里只写了
 * `type: object`，于是 settings.json 里既没有值补全、也没有校验——项目里真有人把它写成
 * `{ "en": "English" }`（把「语言显示名」当成了旗帜名），EN 那一行就显示「?」。
 * 补上 additionalProperties.enum 之后，值有补全、写错直接标红。
 * 键（locale 标识）是动态的，schema 枚举不出来，只能约束值。
 */
async function patchPackageJson(flags: string[]) {
  const pkgPath = path.resolve('./package.json')
  let text = await fs.readFile(pkgPath, 'utf-8')
  const formattingOptions = { insertSpaces: true, tabSize: 2, eol: '\n' }

  /**
   * configuration 可能是单个对象，也可能是多个 category 的数组（当前是 8 个）。
   * 数组时 properties 索引不固定，所以按 setting id 反查它落在第几段，别写死下标。
   */
  const replace = (settingId: string, tail: (string | number)[], value: unknown) => {
    const cats = JSON.parse(text).contributes.configuration
    const isArray = Array.isArray(cats)
    let jsonPath: (string | number)[]
    if (isArray) {
      const idx = (cats as { properties?: Record<string, unknown> }[])
        .findIndex(c => !!c.properties && settingId in c.properties)
      if (idx < 0)
        throw new Error(`package.json 的任一 configuration 段里都找不到设置项 ${settingId}`)
      jsonPath = ['contributes', 'configuration', idx, 'properties', settingId, ...tail]
    }
    else {
      jsonPath = ['contributes', 'configuration', 'properties', settingId, ...tail]
    }
    const edits = modify(text, jsonPath, value, { formattingOptions })
    text = applyEdits(text, edits)
  }

  replace(
    'i18n-ally.localeCountryMap',
    ['additionalProperties'],
    {
      type: 'string',
      enum: flags,
      enumDescriptions: flagDescriptions(flags),
    },
  )

  replace(
    'i18n-ally.translate.localeMap',
    ['properties'],
    Object.fromEntries(
      Object.entries(TRANSLATE_ENGINES).map(([id, label]) => [id, engineLocaleSchema(id, label)]),
    ),
  )

  // 写回前先自检：modify 不该产出坏 JSON，坏在这里报比装进编辑器再报好
  JSON.parse(text)
  await fs.writeFile(pkgPath, text, 'utf-8')
}

;(async() => {
  const files = await fg('./res/flags/*.svg')
  // 排序，否则 fast-glob 的返回顺序随文件系统变化，每次生成都是大片无意义 diff
  const flags = files.map(file => path.basename(file, '.svg')).sort()
  const output = path.resolve('./src/utils/flags.ts')

  await fs.writeFile(output, `// Generated by npm run flags:build\nexport const FLAGS = [\n${flags.map(f => `  '${f}',\n`).join('')}]\n`, 'utf-8')
  await patchPackageJson(flags)

  // eslint-disable-next-line no-console
  console.log(`flags: ${flags.length} 个，已写入 src/utils/flags.ts 与 package.json 的 schema`)
})()
